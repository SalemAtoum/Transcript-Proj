from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from fastapi import APIRouter, HTTPException, status

from src.backend.schemas import (
    SpeakerResponse,
    TranscriptResponse,
    TranscriptTurn,
)


# ============================================================
# Router
# ============================================================

router = APIRouter(
    prefix="/api/meetings",
    tags=["Transcript"],
)


# ============================================================
# Paths
# ============================================================

ROUTES_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = ROUTES_DIR.parents[2]

MEETINGS_DIRECTORY = (
    PROJECT_ROOT
    / "data"
    / "meetings"
)


# ============================================================
# Helpers
# ============================================================

def get_meeting_directory(meeting_id: str) -> Path:
    """
    Return the isolated workspace directory for a meeting.
    """

    return MEETINGS_DIRECTORY / meeting_id


def get_final_transcript_file(meeting_id: str) -> Path:
    """
    Return the final transcript JSON belonging to one meeting.
    """

    return (
        get_meeting_directory(meeting_id)
        / "temporary"
        / "final_transcript.json"
    )


def load_final_transcript(
    meeting_id: str,
) -> dict[str, Any]:
    """
    Load the final transcript generated by the AI pipeline
    for the requested meeting only.
    """

    final_transcript_file = get_final_transcript_file(
        meeting_id
    )

    if not final_transcript_file.exists():
        raise FileNotFoundError(
            "Final transcript was not found:\n"
            f"{final_transcript_file}"
        )

    if not final_transcript_file.is_file():
        raise ValueError(
            "Final transcript path is not a file:\n"
            f"{final_transcript_file}"
        )

    if final_transcript_file.stat().st_size == 0:
        raise ValueError(
            "Final transcript file is empty:\n"
            f"{final_transcript_file}"
        )

    with final_transcript_file.open(
        "r",
        encoding="utf-8",
    ) as file:
        data = json.load(file)

    if not isinstance(data, dict):
        raise ValueError(
            "Final transcript JSON must contain an object."
        )

    return data


# ============================================================
# Duration
# ============================================================

def get_transcript_duration(
    transcript_data: dict[str, Any],
    turns: list[TranscriptTurn],
) -> float:
    """
    Resolve transcript duration robustly.

    Preferred sources:

    1. audio_duration
    2. duration_seconds
    3. duration

    If none of these fields exists or contains a valid value,
    calculate the duration from the latest transcript turn.

    This prevents the public API from incorrectly returning
    0.0 seconds when the final transcript contains valid timing
    information under another field name.
    """

    duration_keys = (
        "audio_duration",
        "duration_seconds",
        "duration",
    )

    for key in duration_keys:

        value = transcript_data.get(
            key
        )

        if value is None:
            continue

        try:
            duration = float(value)

        except (
            TypeError,
            ValueError,
        ):
            continue

        if duration > 0:
            return duration

    # --------------------------------------------------------
    # Fallback:
    # Calculate duration from transcript turns.
    # --------------------------------------------------------

    if turns:

        latest_end = max(
            (
                turn.end_seconds
                for turn in turns
            ),
            default=0.0,
        )

        if latest_end > 0:
            return float(
                latest_end
            )

    return 0.0


# ============================================================
# Build Speakers
# ============================================================

def build_speakers(
    transcript_data: dict[str, Any],
) -> list[SpeakerResponse]:
    """
    Convert the final transcript speaker mapping
    into public API speaker objects.
    """

    speaker_mapping = transcript_data.get(
        "speaker_mapping",
        {},
    )

    statistics = transcript_data.get(
        "statistics",
        {},
    )

    speaker_word_counts = statistics.get(
        "speaker_word_counts",
        {},
    )

    if not isinstance(
        speaker_mapping,
        dict,
    ):
        speaker_mapping = {}

    if not isinstance(
        speaker_word_counts,
        dict,
    ):
        speaker_word_counts = {}

    speakers: list[SpeakerResponse] = []

    for speaker_id, speaker_name in sorted(
        speaker_mapping.items()
    ):
        speaker_id = str(
            speaker_id
        )

        speaker_name = str(
            speaker_name
        )

        identified = (
            speaker_name != "UNKNOWN"
        )

        word_count = int(
            speaker_word_counts.get(
                speaker_name,
                0,
            )
        )

        speakers.append(
            SpeakerResponse(
                id=speaker_id,
                name=speaker_name,
                identified=identified,
                confidence=None,
                word_count=word_count,
            )
        )

    return speakers


# ============================================================
# Build Turns
# ============================================================

def build_turns(
    transcript_data: dict[str, Any],
) -> list[TranscriptTurn]:
    """
    Convert internal final transcript turns
    into the public API transcript format.
    """

    raw_turns = transcript_data.get(
        "turns",
        [],
    )

    if not isinstance(
        raw_turns,
        list,
    ):
        return []

    turns: list[TranscriptTurn] = []

    for turn in raw_turns:

        if not isinstance(
            turn,
            dict,
        ):
            continue

        text = str(
            turn.get(
                "text",
                "",
            )
        ).strip()

        if not text:
            continue

        start = float(
            turn.get(
                "start",
                0.0,
            )
        )

        end = float(
            turn.get(
                "end",
                start,
            )
        )

        speaker = str(
            turn.get(
                "speaker",
                "UNKNOWN",
            )
        )

        turns.append(
            TranscriptTurn(
                speaker=speaker,
                start_seconds=start,
                end_seconds=end,
                text=text,
            )
        )

    return turns


# ============================================================
# GET TRANSCRIPT
# ============================================================

@router.get(
    "/{meeting_id}/transcript",
    response_model=TranscriptResponse,
    status_code=status.HTTP_200_OK,
)
def get_transcript(
    meeting_id: str,
) -> TranscriptResponse:
    """
    Return the completed transcript for one meeting.

    Every meeting reads only from its own isolated
    workspace:

        data/meetings/<meeting_id>/
    """

    # --------------------------------------------------------
    # 1. Validate meeting workspace
    # --------------------------------------------------------

    meeting_directory = get_meeting_directory(
        meeting_id
    )

    if not meeting_directory.exists():

        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=(
                f"Meeting '{meeting_id}' "
                "was not found."
            ),
        )

    if not meeting_directory.is_dir():

        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=(
                f"Meeting '{meeting_id}' "
                "was not found."
            ),
        )

    # --------------------------------------------------------
    # 2. Load meeting-specific transcript
    # --------------------------------------------------------

    try:

        transcript_data = load_final_transcript(
            meeting_id
        )

    except FileNotFoundError:

        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=(
                "Transcript is not available yet. "
                "The meeting may still be processing."
            ),
        )

    except (
        ValueError,
        json.JSONDecodeError,
    ) as error:

        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=(
                "The final transcript could not be read."
            ),
        ) from error

    # --------------------------------------------------------
    # 3. Build API response
    # --------------------------------------------------------

    speakers = build_speakers(
        transcript_data
    )

    turns = build_turns(
        transcript_data
    )

    statistics = transcript_data.get(
        "statistics",
        {},
    )

    if not isinstance(
        statistics,
        dict,
    ):
        statistics = {}

    # --------------------------------------------------------
    # Duration
    # --------------------------------------------------------

    duration = get_transcript_duration(
        transcript_data=transcript_data,
        turns=turns,
    )

    # --------------------------------------------------------
    # Word count
    # --------------------------------------------------------

    word_count = int(
        statistics.get(
            "total_words",
            0,
        ) or 0
    )

    # Fallback to transcript turns if
    # statistics does not contain total_words.

    if word_count == 0:

        word_count = sum(
            len(
                turn.text.split()
            )
            for turn in turns
        )

    # --------------------------------------------------------
    # Language
    # --------------------------------------------------------

    language = str(
        transcript_data.get(
            "language",
            "ar",
        )
    )

    # --------------------------------------------------------
    # 4. Return response
    # --------------------------------------------------------

    return TranscriptResponse(
        meeting_id=meeting_id,
        language=language,
        duration_seconds=duration,
        word_count=word_count,
        speakers=speakers,
        turns=turns,
    )